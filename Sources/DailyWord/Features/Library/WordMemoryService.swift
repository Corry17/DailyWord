    /// 生成趣味记词（词根词缀拆解），找不到返回 nil
    func memory(for word: String) -> String? {
        let w = word.lowercased()
        guard w.count >= 3 else { return nil }

        // 1. 整词即词根
        if let root = roots[w] {
            return "词根记忆：\(w) 本身就是词根，意为「\(root)」"
        }
        // 2. 前缀 + 词根
        for (pre, preMean) in prefixes where w.hasPrefix(pre) {
            let rest = String(w.dropFirst(pre.count))
            if let r = roots[rest], rest.count >= 2 {
                return "词根拆解：\(pre)（\(preMean)）+ \(rest)（\(r)）"
            }
        }
        // 3. 词根 + 后缀
        for (suf, sufMean) in suffixes where w.hasSuffix(suf) {
            let rest = String(w.dropLast(suf.count))
            if let r = roots[rest], rest.count >= 2 {
                return "词根拆解：\(rest)（\(r)）+ \(suf)（\(sufMean)）"
            }
        }
        // 4. 前缀 + 词根 + 后缀
        for (pre, preMean) in prefixes where w.hasPrefix(pre) {
            let mid = String(w.dropFirst(pre.count))
            for (suf, sufMean) in suffixes where mid.hasSuffix(suf) {
                let rest = String(mid.dropLast(suf.count))
                if let r = roots[rest], rest.count >= 2 {
                    return "词根拆解：\(pre)（\(preMean)）+ \(rest)（\(r)）+ \(suf)（\(sufMean)）"
                }
            }
        }
        return nil
    }

