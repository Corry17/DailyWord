            "s": "变体", "2": "变体",
        ]
        var parts: [String] = []
        for pair in raw.split(separator: "/") {
            let kv = pair.split(separator: ":", maxSplits: 1)
            guard kv.count == 2, let key = kv[0].first, let label = labels[key] else { continue }
            parts.append("\(label) \(kv[1])")
        }
        return parts.isEmpty ? nil : parts.joined(separator: " · ")
    }
