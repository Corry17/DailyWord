    /// 批量生成的趣味记忆（词中词/音节分段，加载自本地 JSON）
    private var generatedMemories: [String: String] = [:]
    private var generatedLoaded = false

    private func loadGeneratedMemories() {
        guard !generatedLoaded else { return }
        generatedLoaded = true
        let url = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask).first!
            .appendingPathComponent("fun_memories.json")
        guard let data = try? Data(contentsOf: url),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: String]
        else { return }
        generatedMemories = json
    }

    /// 趣味记词：人工库 → 批量生成库 → 词根词缀拆解
    func funMemory(for word: String) -> String? {
        let key = word.lowercased()
        if let m = funMemories[key] {
            return m
        }
        loadGeneratedMemories()
        if let m = generatedMemories[key] {
            return m
        }
        return memory(for: word)
    }

    /// 常见派生后缀（词干剥离用）
    private static let commonSuffixes = [
        "tion", "sion", "ment", "ness", "ity", "ance", "ence", "hood", "ship", "ism",
        "age", "ure", "al", "ial", "able", "ible", "ful", "less", "ous", "ive", "ic",
        "ary", "ant", "ent", "ish", "ly", "er", "or", "ist", "ian", "ize", "ise",
        "ify", "ate", "en", "ed", "ing",
    ]

    /// 词干记忆：剥离常见派生后缀后，剩余部分在词库中存在 → "词干记忆"
    func stemMemory(for word: String, wordSet: Set<String>) -> String? {
        let w = word.lowercased()
        guard w.count >= 5 else { return nil }
        for suf in Self.commonSuffixes where w.hasSuffix(suf) {
            let stem = String(w.dropLast(suf.count))
            if stem.count >= 3, wordSet.contains(stem) {
                return "词干记忆：\(w) = \(stem)（词库中的词）+ \(suf)（派生后缀）"
            }
        }
        return nil
    }

    /// 拆分记忆：把单词拆成词库中已知的词（如 pineapple = pine + apple）
    func splitMemory(for word: String, wordMeanings: [String: String]) -> String? {
        let w = word.lowercased()
        guard w.count >= 5 else { return nil }
        var parts: [(String, String)] = []
        var rest = w
        while rest.count >= 2 {
            var matched = false
            for len in stride(from: min(10, rest.count), through: 2, by: -1) {
                let sub = String(rest.prefix(len))
                if let mean = wordMeanings[sub] {
                    parts.append((sub, firstLine(mean)))
                    rest = String(rest.dropFirst(len))
                    matched = true
                    break
                }
            }
            if !matched { return nil }
        }
        guard parts.count >= 2 else { return nil }
        let joined = parts.map { "\($0.0)（\($0.1)）" }.joined(separator: " + ")
        return "拆分记忆：\(joined)"
    }

    /// 考纲/词频兜底信息（无趣味记忆时展示，如 "四级 · 高频词"）
    func tagText(for word: Word) -> String? {
        var parts: [String] = []
        if let tags = word.tags, !tags.isEmpty {
            let map = ["zk": "中考", "gk": "高考", "cet4": "四级", "cet6": "六级",
                       "ky": "考研", "ielts": "雅思", "toefl": "托福", "gre": "GRE",
                       "pte": "PTE", "bec": "BEC", "catti": "CATTI"]
            let known = tags.split(separator: " ").compactMap { map[String($0)] }
            if !known.isEmpty { parts.append(known.joined(separator: "/")) }
        }
        if let freq = word.frequency {
            let level = freq > 3000 ? "高频" : (freq > 1000 ? "中频" : "低频")
            parts.append("\(level)词")
        }
        guard !parts.isEmpty else { return nil }
        return parts.joined(separator: " · ")
    }

