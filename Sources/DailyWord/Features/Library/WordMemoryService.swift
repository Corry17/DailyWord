    /// 同词根词：找出与当前词共享词根的词（自动从词表匹配，最多 6 个）
    func sameRootWords(for word: String, wordList: [String]) -> [String] {
        let w = word.lowercased()
        var myRoots: [String] = []
        if roots[w] != nil {
            myRoots = [w]
        } else {
            for (pre, _) in prefixes where w.hasPrefix(pre) {
                let rest = String(w.dropFirst(pre.count))
                if roots[rest] != nil { myRoots.append(rest) }
            }
            if myRoots.isEmpty {
                for (suf, _) in suffixes where w.hasSuffix(suf) {
                    let rest = String(w.dropLast(suf.count))
                    if roots[rest] != nil { myRoots.append(rest) }
                }
            }
        }
        guard let root = myRoots.first, root.count >= 2 else { return [] }
        let result = wordList
            .filter { $0.lowercased().hasPrefix(root) && $0.lowercased() != w }
            .prefix(6)
            .map { $0 }
        return result.isEmpty ? [] : result
    }

